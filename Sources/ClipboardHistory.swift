import AppKit
import CryptoKit

/// Ein Eintrag im allgemeinen Zwischenablage-Verlauf (⌃V).
struct ClipEntry: Codable, Identifiable, Sendable {
    enum Kind: String, Codable, Sendable { case text, url, image, files }
    var id = UUID()
    var kind: Kind
    var key: String          // Inhalts-Fingerabdruck für „Doppelte zusammenführen“
    var text: String?        // Text oder Link
    var paths: [String]?     // Dateien (nur Pfade)
    var image: String?       // PNG in clipboard/images/
    var meta: String?        // z. B. „800×600“
    var date = Date()
    var app: String?
    var bundle: String?
    var pinned = false

    var searchText: String { [text, paths?.map { ($0 as NSString).lastPathComponent }.joined(separator: " "), meta, app].compactMap { $0 }.joined(separator: " ") }
}

extension ClipEntry {
    /// Altes Schema: `id`, `date`, `pinned` haben Ersatzwerte; `kind` und `key` bleiben Pflicht.
    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.decodeIfPresent(UUID.self, forKey: .id) ?? UUID()
        kind = try c.decode(Kind.self, forKey: .kind)
        key = try c.decode(String.self, forKey: .key)
        text = try c.decodeIfPresent(String.self, forKey: .text)
        paths = try c.decodeIfPresent([String].self, forKey: .paths)
        image = try c.decodeIfPresent(String.self, forKey: .image)
        meta = try c.decodeIfPresent(String.self, forKey: .meta)
        date = try c.decodeIfPresent(Date.self, forKey: .date) ?? PersistedList.unknownDate
        app = try c.decodeIfPresent(String.self, forKey: .app)
        bundle = try c.decodeIfPresent(String.self, forKey: .bundle)
        pinned = try c.decodeIfPresent(Bool.self, forKey: .pinned) ?? false
    }
}

/// Verlauf + Wächter. Der Wächter vergleicht nur `changeCount` (alle 0,5 s, Toleranz 0,2 s) und liest Inhalte erst bei Änderung.
/// Speicher: Application Support/DropShelf/clipboard/ (index.json, images/), verzögert geschrieben.
@MainActor
final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()
    static let skipTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
                                         "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type"]
    /// Immer aktiv, unabhängig von der eigenen Ausschlussliste. IDs aus den Info.plist der installierten Apps.
    static let denylist: Set<String> = ["com.apple.Passwords", "com.apple.keychainaccess"]
    static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")
    static let maxText = 100_000  // Zeichen
    static let textLifetime: TimeInterval = 24 * 60 * 60  // nicht angepinnter Text
    static let pauseDuration: TimeInterval = 5 * 60

    struct Captured: Sendable { var entry: ClipEntry; var png: Data? }

    @Published private(set) var entries: [ClipEntry] = []
    @Published private(set) var pausedUntil: Date?
    @Published private(set) var unreadable = false  // index.json ist da, aber nicht lesbar: nur „Verlauf löschen“ gibt das Speichern wieder frei
    var limitOverride: Int?  // nur Selbsttest
    private let dir: URL
    private var timer: Timer?
    private var expiryTimer: Timer?
    private var pendingClear: Bool?  // „Verlauf löschen“ vor Ende des Ladens; true = auch Angepinnte
    private var lastCount = 0
    private var ownCount = -1  // changeCount nach unserem eigenen Schreiben: nicht erneut erfassen
    private var saveWork: DispatchWorkItem?
    private var loadStarted = false
    private(set) var loaded = false  // erst true, wenn der Verlauf gelesen ist und überschrieben werden darf

    static var enabled: Bool { UserDefaults.standard.object(forKey: "clipboardEnabled") as? Bool ?? true }
    static var limit: Int { UserDefaults.standard.object(forKey: "clipboardLimit") as? Int ?? 200 }
    static var keepImages: Bool { UserDefaults.standard.object(forKey: "clipboardImages") as? Bool ?? true }
    static var excluded: [String] {
        get { UserDefaults.standard.stringArray(forKey: "clipboardExcluded") ?? [] }
        set { UserDefaults.standard.set(newValue, forKey: "clipboardExcluded") }
    }

    init(dir: URL? = nil) {
        self.dir = dir ?? FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("DropShelf/clipboard", isDirectory: true)
        try? FileManager.default.createDirectory(at: self.dir.appendingPathComponent("images"), withIntermediateDirectories: true)
        var backup = URLResourceValues()
        backup.isExcludedFromBackup = true
        var target = self.dir  // gilt für den ganzen Ordner und übersteht so atomares Schreiben von index.json
        try? target.setResourceValues(backup)
    }

    // MARK: Wächter

    /// Startet/stoppt den Timer je nach Einstellung. Geladen wird immer (im Hintergrund), damit alter Text auch bei ausgeschalteter Aufzeichnung abläuft.
    func sync() {
        timer?.invalidate(); timer = nil
        load()
        if expiryTimer == nil {
            let t = Timer(timeInterval: 60, repeats: true) { [weak self] _ in MainActor.assumeIsolated { self?.expire() } }
            t.tolerance = 10
            RunLoop.main.add(t, forMode: .common)
            expiryTimer = t
        }
        guard Self.enabled else { pausedUntil = nil; return }
        lastCount = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in MainActor.assumeIsolated { self?.poll() } }
        t.tolerance = 0.2
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func poll(_ pb: NSPasteboard = .general, now: Date = Date()) {
        let c = pb.changeCount
        if let until = pausedUntil {  // Inhalt nie lesen, nur den Zähler mitführen: Kopiertes bleibt auch nach der Pause draußen
            lastCount = c
            if now >= until { pausedUntil = nil }
            return
        }
        guard c != lastCount else { return }  // Leerlauf: nur dieser Vergleich
        lastCount = c
        guard c != ownCount else { return }
        let app = NSWorkspace.shared.frontmostApplication
        if let b = app?.bundleIdentifier, Self.excluded.contains(b) || Self.denylist.contains(b) { return }
        ingest(pb, app: app, expectedCount: c)
    }

    func pause(now: Date = Date()) { pausedUntil = now.addingTimeInterval(Self.pauseDuration) }

    func endPause(_ pb: NSPasteboard = .general) {
        lastCount = pb.changeCount
        pausedUntil = nil
    }

    func ingest(_ pb: NSPasteboard, app: NSRunningApplication?, expectedCount: Int? = nil) {
        guard let cap = Self.capture(pb, images: Self.keepImages, expectedCount: expectedCount) else { return }
        add(cap, app: app)
    }

    /// Verwirft das Gelesene, wenn sich die Zwischenablage seit `expectedCount` geändert hat (Marker und Inhalt könnten sonst von verschiedenen Kopien stammen).
    static func capture(_ pb: NSPasteboard, images: Bool, expectedCount: Int? = nil) -> Captured? {
        let count = expectedCount ?? pb.changeCount
        let cap = read(pb, images: images)
        return pb.changeCount == count ? cap : nil
    }

    /// Liest den Inhalt: vertrauliche/flüchtige Typen oder gesperrte Quelle → nil; Dateien vor Bild vor Text/Link.
    private static func read(_ pb: NSPasteboard, images: Bool) -> Captured? {
        let types = (pb.types ?? []).map(\.rawValue)
        guard Set(types).isDisjoint(with: skipTypes) else { return nil }
        if let source = pb.string(forType: sourceType), denylist.contains(source) { return nil }
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let p = urls.map(\.path)
            return Captured(entry: ClipEntry(kind: .files, key: "f:" + p.joined(separator: "\n"), paths: p), png: nil)
        }
        let s = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines)
        let isLink = s.map { ($0.hasPrefix("http://") || $0.hasPrefix("https://")) && !$0.contains(where: \.isWhitespace) } ?? false
        if images, s == nil || isLink, let raw = pb.data(forType: .png) ?? pb.data(forType: .tiff), raw.count < 40_000_000,
           let (png, meta) = pngData(raw) {
            let hash = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
            return Captured(entry: ClipEntry(kind: .image, key: "i:" + hash, meta: meta), png: png)
        }
        guard var s, !s.isEmpty else { return nil }
        if s.count > maxText { s = String(s.prefix(maxText)) }
        return Captured(entry: ClipEntry(kind: isLink ? .url : .text, key: (isLink ? "u:" : "t:") + s, text: s), png: nil)
    }

    /// PNG (große Bilder auf höchstens 2400 px Kantenlänge verkleinert) + Größenangabe des Originals.
    private static func pngData(_ data: Data) -> (Data, String)? {
        guard let rep = NSBitmapImageRep(data: data) else { return nil }
        let w = rep.pixelsWide, h = rep.pixelsHigh, m = max(w, h)
        var out = rep
        if m > 2400 {
            let s = 2400.0 / Double(m), nw = Int(Double(w) * s), nh = Int(Double(h) * s)
            if let r = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: nw, pixelsHigh: nh, bitsPerSample: 8, samplesPerPixel: 4,
                                        hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0),
               let ctx = NSGraphicsContext(bitmapImageRep: r) {
                NSGraphicsContext.saveGraphicsState()
                NSGraphicsContext.current = ctx
                rep.draw(in: NSRect(x: 0, y: 0, width: nw, height: nh))
                NSGraphicsContext.restoreGraphicsState()
                out = r
            }
        }
        guard let png = out.representation(using: .png, properties: [:]) else { return nil }
        return (png, "\(w)×\(h)")
    }

    // MARK: Verlauf

    /// Neuer Inhalt nach vorn; gleicher Inhalt wird nur nach oben geholt (Pin und Bild bleiben).
    func add(_ cap: Captured, app: NSRunningApplication?, now: Date = Date()) {
        var e = cap.entry
        e.date = now; e.app = app?.localizedName; e.bundle = app?.bundleIdentifier
        if let i = entries.firstIndex(where: { $0.key == e.key }) {
            var old = entries.remove(at: i)
            old.date = now; old.app = e.app; old.bundle = e.bundle
            entries.insert(old, at: 0)
        } else {
            if let png = cap.png {
                let name = e.id.uuidString + ".png"
                guard (try? png.write(to: dir.appendingPathComponent("images/" + name))) != nil else { return }
                e.image = name
            }
            entries.insert(e, at: 0)
        }
        trim(now: now)
    }

    /// Angepinnte zählen mit, werden aber nie entfernt.
    func trim(now: Date = Date()) {
        expire(now: now)
        let limit = limitOverride ?? Self.limit
        while entries.count > limit, let i = entries.lastIndex(where: { !$0.pinned }) { drop(i) }
        scheduleSave()
    }

    /// Entfernt nicht angepinnten Text nach 24 h, auch von der Platte.
    func expire(now: Date = Date()) {
        let before = entries.count
        for i in entries.indices.reversed()
        where !entries[i].pinned && entries[i].kind == .text && now.timeIntervalSince(entries[i].date) >= Self.textLifetime { drop(i) }
        if entries.count != before { flush() }
    }

    private func drop(_ i: Int) {
        let e = entries.remove(at: i)
        if let img = e.image { try? FileManager.default.removeItem(at: dir.appendingPathComponent("images/" + img)) }
    }

    func remove(_ id: UUID) {
        if let i = entries.firstIndex(where: { $0.id == id }) { drop(i); flush() }
    }

    func togglePin(_ id: UUID) {
        if let i = entries.firstIndex(where: { $0.id == id }) { entries[i].pinned.toggle(); scheduleSave() }
    }

    /// „Verlauf löschen“: Angepinnte bleiben, außer `pinned` ist true.
    /// Bei unlesbarer index.json wird die Datei samt fremder Bilder gelöscht (ihre Pins sind nicht erkennbar); danach wird wieder gespeichert.
    func clear(includingPinned pinned: Bool) {
        for i in entries.indices.reversed() where pinned || !entries[i].pinned { drop(i) }
        if unreadable {
            let fm = FileManager.default
            try? fm.removeItem(at: index)
            let keep = Set(entries.compactMap(\.image))
            let images = (try? fm.contentsOfDirectory(at: dir.appendingPathComponent("images"), includingPropertiesForKeys: nil)) ?? []
            for f in images where !keep.contains(f.lastPathComponent) { try? fm.removeItem(at: f) }
            if !fm.fileExists(atPath: index.path) { unreadable = false; loaded = true }
        } else if !loaded {
            pendingClear = pinned || pendingClear == true  // Laden läuft noch: gleich danach nachholen
        }
        flush()
    }

    func imageURL(_ e: ClipEntry) -> URL? { e.image.map { dir.appendingPathComponent("images/" + $0) } }

    /// Legt den Eintrag in die Zwischenablage (eigener changeCount wird nicht erneut erfasst) und holt ihn nach oben.
    func copy(_ e: ClipEntry) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch e.kind {
        case .text: pb.setString(e.text ?? "", forType: .string)
        case .url:
            if let u = e.text.flatMap(URL.init(string:)) { pb.writeObjects([u as NSURL]) }
            pb.setString(e.text ?? "", forType: .string)
        case .image: if let u = imageURL(e), let img = NSImage(contentsOf: u) { pb.writeObjects([img]) }
        case .files: pb.writeObjects((e.paths ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        }
        ownCount = pb.changeCount
        lastCount = ownCount
        if let i = entries.firstIndex(where: { $0.id == e.id }) {
            var x = entries.remove(at: i); x.date = Date(); entries.insert(x, at: 0); scheduleSave()
        }
    }

    // MARK: Speicher

    private var index: URL { dir.appendingPathComponent("index.json") }

    func load() {
        guard !loadStarted else { return }
        loadStarted = true
        let url = index
        Task.detached(priority: .utility) { [weak self] in
            let (list, writable): ([ClipEntry], Bool) = PersistedList.load(url, keepBackup: false)
            await MainActor.run {
                guard let self else { return }
                let have = Set(self.entries.map(\.key))
                self.entries += list.filter { !have.contains($0.key) }.sorted { $0.date > $1.date }
                self.loaded = writable
                self.unreadable = !writable
                if let all = self.pendingClear { self.pendingClear = nil; self.clear(includingPinned: all) }
                self.trim()
            }
        }
    }

    private func scheduleSave() {
        saveWork?.cancel()
        let w = DispatchWorkItem { [weak self] in MainActor.assumeIsolated { self?.flush() } }
        saveWork = w
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.0, execute: w)
    }

    func flush() {
        saveWork?.cancel(); saveWork = nil
        guard loaded else { return }  // nie einen noch nicht geladenen oder unlesbaren Verlauf überschreiben
        if let data = try? JSONEncoder().encode(entries) { try? data.write(to: index, options: .atomic) }
    }

    static func appName(_ bundleID: String) -> String {
        NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID).map { FileManager.default.displayName(atPath: $0.path) } ?? bundleID
    }

    #if DEBUG
    /// Ohne UI, auf eigenem Test-Pasteboard: Doppelte, Kürzen mit Pins, vertrauliche Typen.
    static func selfCheck() {
        let tmp = FileManager.default.temporaryDirectory.appendingPathComponent("dropshelf-clip-" + UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: tmp) }
        let s = ClipboardStore(dir: tmp)
        s.loaded = true
        let pb = NSPasteboard(name: .init("DropShelf.selftest"))
        func copy(_ t: String, _ extra: [String] = []) {
            pb.clearContents(); pb.setString(t, forType: .string)
            extra.forEach { pb.setData(Data([0]), forType: .init($0)) }
            s.ingest(pb, app: nil)
        }
        copy("a"); copy("b"); copy("a")
        assert(s.entries.map(\.text) == ["a", "b"], "dedupe")
        copy("geheim", ["org.nspasteboard.ConcealedType"]); copy("flüchtig", ["org.nspasteboard.TransientType"])
        assert(s.entries.count == 2, "concealed/transient")
        s.togglePin(s.entries[1].id)  // „b“ angepinnt
        s.limitOverride = 2
        copy("c"); copy("d")
        assert(s.entries.map(\.text) == ["d", "b"], "trim keeps pins: \(s.entries.map(\.text))")
        copy("https://example.com")
        assert(s.entries.first?.kind == .url, "url")
        s.clear(includingPinned: false)
        assert(s.entries.map(\.text) == ["b"], "clear keeps pins")
        NSLog("CLIPBOARD-SELFCHECK ok")
    }
    #endif
}
